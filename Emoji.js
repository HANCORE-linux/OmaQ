function inRanges(codePoint, ranges) {
  var low = 0
  var high = ranges.length / 2 - 1
  while (low <= high) {
    var middle = Math.floor((low + high) / 2)
    var start = ranges[middle * 2]
    var end = ranges[middle * 2 + 1]
    if (codePoint < start)
      high = middle - 1
    else if (codePoint > end)
      low = middle + 1
    else
      return true
  }
  return false
}

function consumeEmojiBase(text, offset, joined) {
  var codePoint = pointAt(text, offset)
  if (codePoint < 0)
    return -1
  var next = offset + codePointLength(codePoint)

  if (!joined && (codePoint === 0x23 || codePoint === 0x2a ||
      (codePoint >= 0x30 && codePoint <= 0x39))) {
    if (pointAt(text, next) === 0xfe0f)
      next++
    return pointAt(text, next) === 0x20e3 ? next + 1 : -1
  }

  if (!joined && isRegionalIndicator(codePoint)) {
    var second = pointAt(text, next)
    return isRegionalIndicator(second) ? next + codePointLength(second) : -1
  }
  if (isRegionalIndicator(codePoint) || isEmojiModifier(codePoint) ||
      !inRanges(codePoint, emojiCharacterRanges) ||
      (joined && !inRanges(codePoint, extendedPictographicRanges)))
    return -1

  var presentation = inRanges(codePoint, emojiPresentationRanges)
  var variation = pointAt(text, next)
  if (variation === 0xfe0e)
    return -1
  if (variation === 0xfe0f)
    next++
  else if (!presentation)
    return -1

  var modifier = pointAt(text, next)
  if (isEmojiModifier(modifier)) {
    if (!inRanges(codePoint, emojiModifierBaseRanges))
      return -1
    next += codePointLength(modifier)
  }
  return next
}

function consumeEmoji(text, offset) {
  var firstCodePoint = pointAt(text, offset)
  var next = consumeEmojiBase(text, offset, false)
  if (next < 0)
    return -1

  var tag = pointAt(text, next)
  if (tag >= 0xe0061 && tag <= 0xe007a) {
    if (firstCodePoint !== 0x1f3f4)
      return -1
    while ((tag = pointAt(text, next)) >= 0xe0061 && tag <= 0xe007a)
      next += codePointLength(tag)
    if (pointAt(text, next) !== 0xe007f)
      return -1
    next += codePointLength(0xe007f)
  }

  while (pointAt(text, next) === 0x200d) {
    if (!inRanges(firstCodePoint, extendedPictographicRanges))
      return -1
    var joined = consumeEmojiBase(text, next + 1, true)
    if (joined < 0)
      return -1
    next = joined
  }
  return next
}

function splitEmojiOnly(value) {
  var text = String(value || "")
  var result = []
  var offset = 0
  while (offset < text.length) {
    var codePoint = pointAt(text, offset)
    if (codePoint === 0x20 || codePoint === 0x09 ||
        codePoint === 0x0a || codePoint === 0x0d) {
      offset += codePointLength(codePoint)
      continue
    }
    var next = consumeEmoji(text, offset)
    if (next <= offset)
      return []
    result.push(text.slice(offset, next))
    offset = next
  }
  return result
}
